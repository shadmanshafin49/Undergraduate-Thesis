"""
experiments/write_b2_draft.py
=============================
B2 deliverable — turn the REAL Fabric measurements
(results/fabric_consensus_measured.json, produced by
db_boa_fabric/api-server/measure_consensus.js against the live test-network)
into a markdown draft in final_report_data/, replacing the fabricated
85 TPS / 180 ms / 28.4% consensus figures (divergence D7).
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
from config import RESULTS_DIR

src = os.path.join(RESULTS_DIR, "fabric_consensus_measured.json")
with open(src) as f:
    d = json.load(f)

lat, tp = d["latency_ms"], d["throughput"]
L = []
L.append("# B2 — Real Hyperledger Fabric Consensus Measurement\n")
L.append("_Auto-generated by `experiments/write_b2_draft.py` from "
         "`results/fabric_consensus_measured.json`, measured by "
         "`db_boa_fabric/api-server/measure_consensus.js` against the **live** "
         "Fabric test-network via the fabric-network SDK gateway. Replaces the "
         "previously fabricated 85 TPS / 180 ms consensus figures (divergence "
         "D7). Drafts-before-tex workflow._\n")
L.append(f"**Network under test.** {d['network']['orderer']} orderer, "
         f"{d['network']['orgs']} orgs / {d['network']['peers']} peers, "
         f"{d['network']['state_db']} state DB. Timed interval = full "
         f"propose→endorse→order→commit; `peer` CLI process-spawn excluded "
         f"(SDK gateway, persistent connection).\n")
L.append("## Consensus-round latency (real, sequential `recordConsensusRound`)\n")
L.append(f"- **mean {lat['mean_ms']:.0f} ms**, p50 {lat['p50_ms']:.0f} ms, "
         f"p95 {lat['p95_ms']:.0f} ms (min {lat['min_ms']:.0f}, "
         f"max {lat['max_ms']:.0f}), n={lat['n']}.")
L.append(f"- The ~{lat['mean_ms']/1000:.1f} s floor at low load is the Fabric "
         f"**orderer BatchTimeout** (default 2 s): with one transaction in "
         f"flight the orderer waits the full timeout before cutting a block. "
         f"This is real, characteristic Raft-orderer behaviour, not a tuned "
         f"number.\n")
L.append("## Sustained throughput (real, concurrency sweep, contention-free keys)\n")
L.append("`updateNodeMetrics` across the 10 distinct `NODE_*` keys (no shared "
         "counter → no MVCC hotspot), so the figure reflects Fabric "
         "ordering/commit throughput, not chaincode counter-serialisation. Only "
         "VALID (committed) transactions counted.\n")
L.append("| Concurrency | Committed/Total | Failed | Elapsed (s) | Throughput (tps) |")
L.append("|---|---|---|---|---|")
for r in tp:
    L.append(f"| {r['concurrency']} | {r['committed']}/{r['total']} | "
             f"{r['failed']} | {r['elapsed_s']:.2f} | {r['tps']:.1f} |")
L.append("")
L.append(f"- **Peak sustained throughput: {d['peak_tps']:.1f} tps** "
         f"@ concurrency {d['peak_tps_concurrency']}.")
L.append(f"- **Clean region (concurrency 1→{d['peak_tps_concurrency']}):** 0 "
         f"failures, throughput rises ~80× (0.5→{d['peak_tps']:.0f} tps). At low "
         f"concurrency each txn pays the full 2 s BatchTimeout; as more txns "
         f"arrive within one timeout window the orderer batches them into a "
         f"single block, amortising the timeout — the classic Fabric "
         f"latency/throughput trade-off, here measured not assumed.")
L.append(f"- **MVCC knee (concurrency > {d['peak_tps_concurrency']}):** beyond "
         f"the number of independent keys (10 `NODE_*`), concurrent txns "
         f"targeting the *same* key within one block fail validation with "
         f"`MVCC_READ_CONFLICT` (50% fail @ conc 20, 70% @ conc 40). Goodput "
         f"therefore peaks when concurrency ≈ the number of conflict-free keys — "
         f"a real, transferable property of Fabric's optimistic-concurrency "
         f"(read-set/write-set) validation, not a tuning artefact.\n")
L.append("## Honest scope\n")
L.append("- Single-host test-network (2 orgs); not a geo-distributed multi-bank "
         "deployment. Absolute tps is hardware/− and BatchTimeout-bound, so the "
         "*shape* (batching amortises the timeout) is the transferable result, "
         "not the constant.\n- Consensus itself is **stock Fabric Raft**; our "
         "contribution is the RL-governed leader-selection + incentive layer "
         "running on top, now reporting these **measured** numbers "
         "(`leader_block.py`, `use_measured_consensus=True`).")

out = os.path.abspath(os.path.join(ROOT, "..", "final_report_data",
                                   "B2_fabric_consensus_measured.md"))
with open(out, "w") as f:
    f.write("\n".join(L))
print(f"[B2] wrote draft → {out}")
